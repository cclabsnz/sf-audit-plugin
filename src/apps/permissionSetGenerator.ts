import { join } from 'node:path';
import { secureFs } from '@cclabsnz/sf-core';
import type { AppFinding } from './types.js';

const API_NAME_MAX = 80;
const LABEL_MAX = 80;
const NAME_SUFFIX = '_LeastPrivilege';
const LABEL_SUFFIX = ' Least Privilege';

// XML 1.0 forbids most C0 control characters even when escaped; drop them rather than emit invalid XML.
// eslint-disable-next-line no-control-regex
const XML_INVALID = /[\u0000-\u0008\u000B\u000C\u000E-\u001F￾￿]/g;

function xmlEscape(s: string): string {
  return s
    .replace(XML_INVALID, '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

/**
 * Turns an app name into a valid metadata API name stem: starts with a letter, only alphanumerics and
 * single underscores, no leading or trailing underscore. Length is capped by the caller.
 */
export function sanitizePermissionSetName(name: string): string {
  let clean = name.replace(/[^a-zA-Z0-9]+/g, '_').replace(/^_+|_+$/g, '');
  if (!clean) return 'App';
  if (!/^[a-zA-Z]/.test(clean)) clean = `App_${clean}`;
  return clean;
}

function fitName(stem: string, tail: string): string {
  const room = API_NAME_MAX - tail.length;
  return `${stem.slice(0, room).replace(/_+$/, '')}${tail}`;
}

/**
 * One API name per finding, unique case-insensitively (Salesforce API names and macOS/Windows file
 * names both ignore case), each at most 80 characters.
 */
export function permissionSetNames(findings: AppFinding[]): string[] {
  const taken = new Set<string>();
  return findings.map((f) => {
    const stem = sanitizePermissionSetName(f.app.name || f.app.appId);
    let candidate = fitName(stem, NAME_SUFFIX);
    for (let n = 2; taken.has(candidate.toLowerCase()); n++) candidate = fitName(stem, `${NAME_SUFFIX}_${n}`);
    taken.add(candidate.toLowerCase());
    return candidate;
  });
}

export function generatePermissionSetXml(finding: AppFinding): string {
  const appName = (finding.app.name || finding.app.appId).replace(XML_INVALID, '');
  const label = `${appName.slice(0, LABEL_MAX - LABEL_SUFFIX.length).trimEnd()}${LABEL_SUFFIX}`;
  const perms = (finding.recommendation?.permissionSet?.objectPermissions ?? [])
    .slice()
    .sort((a, b) => a.object.localeCompare(b.object));

  // Salesforce rejects edit/create without read and delete without edit, so imply the prerequisites.
  const objectXml = perms
    .map((p) => {
      const edit = p.edit || p.delete;
      const read = p.read || p.create || edit;
      return `    <objectPermissions>
        <allowCreate>${p.create}</allowCreate>
        <allowDelete>${p.delete}</allowDelete>
        <allowEdit>${edit}</allowEdit>
        <allowRead>${read}</allowRead>
        <modifyAllRecords>false</modifyAllRecords>
        <object>${xmlEscape(p.object)}</object>
        <viewAllRecords>false</viewAllRecords>
    </objectPermissions>`;
    })
    .join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>
<PermissionSet xmlns="http://soap.sforce.com/2006/04/metadata">
    <description>${xmlEscape(
      `Generated by sf audit apps from usage observed over ${finding.window.since} day(s). Review before deploying.`,
    )}</description>
    <hasActivationRequired>false</hasActivationRequired>
    <label>${xmlEscape(label)}</label>
${objectXml ? objectXml + '\n' : ''}</PermissionSet>
`;
}

/**
 * Writes one .permissionset-meta.xml per finding whose recommendation is asserted. Findings held back
 * (soak window, many interactive users, incomplete logs) are skipped: their observed usage is too thin
 * to be a least-privilege grant. Local files only; nothing is deployed.
 */
export function emitPermissionSets(findings: AppFinding[], targetDir: string): { written: string[]; skipped: string[] } {
  const emit = findings.filter((f) => f.recommendation.asserted);
  const skipped = findings.filter((f) => !f.recommendation.asserted).map((f) => f.app.name || f.app.appId);
  const written: string[] = [];
  if (emit.length === 0) return { written, skipped };

  secureFs.mkdirSync(targetDir, { recursive: true });
  const names = permissionSetNames(emit);
  emit.forEach((f, i) => {
    const filePath = join(targetDir, `${names[i]}.permissionset-meta.xml`);
    secureFs.writeFileSync(filePath, generatePermissionSetXml(f));
    written.push(filePath);
  });
  return { written, skipped };
}
